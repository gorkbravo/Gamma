@dataclass
class MockCopilotProvider(CopilotProvider):
    model: str = "gamma-mock-research-card-v1"
    provider_name: str = "mock"

    def stream_research_card(
        self,
        *,
        request: CopilotResearchCardRequest,
        context: CopilotContextBundle,
        tool_specs: list[dict[str, object]],
        execute_tool: ToolExecutor,
        emit: RunEventEmitter,
        should_cancel: CancelCheck,
    ) -> CopilotResearchCardResult:
        """Deterministic streaming variant: emits tool and text-delta events
        around the same card the synchronous path produces."""

        def traced_execute(tool_name: str, arguments: dict[str, object], ctx: CopilotContextBundle):
            if should_cancel():
                raise CopilotRunCancelled()
            emit("tool.call", {"tool_name": tool_name, "arguments": arguments})
            execution = execute_tool(tool_name, arguments, ctx)
            emit(
                "tool.result",
                {
                    "tool_name": tool_name,
                    "summary": execution.trace.summary,
                    "source_ids": list(execution.trace.source_ids),
                },
            )
            return execution

        result = self.generate_research_card(
            request=request,
            context=context,
            tool_specs=tool_specs,
            execute_tool=traced_execute,
        )
        text = result.card.hypothesis if result.card is not None else (result.message or "")
        for start in range(0, len(text), 48):
            if should_cancel():
                raise CopilotRunCancelled()
            emit("text.delta", {"delta": text[start : start + 48]})
        return result

    def generate_research_card(
        self,
        *,
        request: CopilotResearchCardRequest,
        context: CopilotContextBundle,
        tool_specs: list[dict[str, object]],
        execute_tool: ToolExecutor,
    ) -> CopilotResearchCardResult:
        allowed_tool_names = {
            str(spec.get("name") or "").strip()
            for spec in tool_specs
            if isinstance(spec, dict)
        }
        tool_outputs: dict[str, Any] = {}
        tool_traces: list[CopilotToolTrace] = []
        sources: dict[str, CopilotSourceRef] = {source.source_id: source for source in context.sources}
        extra_warnings: list[str] = []

        for tool_name, arguments in self._planned_tool_calls(context):
            if tool_name not in allowed_tool_names:
                continue
            execution = execute_tool(tool_name, arguments, context)
            tool_traces.append(execution.trace)
            for source in execution.sources:
                sources[source.source_id] = source
            if isinstance(execution.output, dict) and isinstance(execution.output.get("error"), str):
                extra_warnings.append(f"{tool_name}: {execution.output['error']}")
                continue
            if tool_name in tool_outputs:
                existing_output = tool_outputs[tool_name]
                if isinstance(existing_output, list):
                    existing_output.append(execution.output)
                else:
                    tool_outputs[tool_name] = [existing_output, execution.output]
            else:
                tool_outputs[tool_name] = execution.output

        card = self._build_card(request=request, context=context, tool_outputs=tool_outputs, tool_traces=tool_traces)
        response_id = self._response_id(request)
        warnings = dedupe_warnings(
            context.warnings,
            extra_warnings,
            ["Generated by Gamma's local mock Copilot provider; no external model inference was used."],
        )
        return CopilotResearchCardResult(
            domain=request.domain,
            current_tab=context.current_tab,
            status="ready",
            provider=self.provider_name,
            model=self.model,
            response_id=response_id,
            card=card,
            sources=list(sources.values()),
            tool_traces=tool_traces,
            warnings=warnings,
        )

    def _planned_tool_calls(self, context: CopilotContextBundle) -> list[tuple[str, dict[str, Any]]]:
        domain = context.domain
        if domain == "portfolio":
            return [
                ("get_portfolio_positions_summary", {}),
                ("get_portfolio_performance_context", {}),
            ]
        if domain == "research":
            return [
                ("get_research_scope_summary", {}),
                ("get_research_coverage_context", {}),
            ]
        if domain == "strategy_lab":
            calls: list[tuple[str, dict[str, Any]]] = [("get_strategy_lab_handoff_context", {})]
            if any(context.tool_state.get(key) for key in ("composition", "imported_result", "compare_result")):
                calls.append(("run_strategy_lab_backtest", {"result_kind": "auto"}))
            return calls
        if domain == "macro":
            calls: list[tuple[str, dict[str, Any]]] = [("get_macro_workspace_drilldown", {})]
            series_id = self._infer_macro_series_id(context.summary_data)
            if series_id:
                calls.append(("get_macro_series_history_summary", {"series_id": series_id, "region": None}))
            return calls
        if domain == "commodities":
            return [("get_commodities_workspace_summary", {})]
        if domain == "prediction_markets":
            return [
                ("get_prediction_market_history_summary", {}),
                ("get_prediction_market_flow_context", {}),
            ]
        if domain == "crypto":
            return [
                ("get_crypto_price_history_summary", {}),
                ("get_crypto_liquidity_context", {}),
                ("get_crypto_comparison_context", {}),
            ]
        if domain == "fundamentals":
            return [
                ("get_fundamentals_company_context", {}),
                ("get_fundamentals_statement_context", {}),
                ("get_fundamentals_peer_context", {}),
                ("get_fundamentals_dcf_context", {}),
                ("get_fundamentals_reverse_valuation_context", {}),
            ]
        if domain == "risk":
            return [
                ("get_risk_coverage_summary", {}),
                ("get_risk_contribution_summary", {}),
            ]
        if domain == "iv":
            return [
                ("get_iv_surface_context", {}),
                ("get_iv_session_status", {}),
            ]
        if domain == "synthesis":
            calls: list[tuple[str, dict[str, Any]]] = [("get_synthesis_scope_summary", {})]
            for item in self._as_list(context.summary_data.get("included_contexts")):
                included_domain = str(self._as_dict(item).get("domain") or "").strip()
                if included_domain:
                    calls.append(("get_synthesis_domain_context", {"domain": included_domain}))
            return calls
        return []

    def _build_card(
        self,
        *,
        request: CopilotResearchCardRequest,
        context: CopilotContextBundle,
        tool_outputs: dict[str, Any],
        tool_traces: list[CopilotToolTrace],
    ) -> ResearchCard:
        domain = context.domain
        if domain == "portfolio":
            return self._build_portfolio_card(request, context, tool_outputs, tool_traces)
        if domain == "research":
            return self._build_research_card(request, context, tool_outputs, tool_traces)
        if domain == "macro":
            return self._build_macro_card(request, context, tool_outputs, tool_traces)
        if domain == "commodities":
            return self._build_commodities_card(request, context, tool_outputs, tool_traces)
        if domain == "prediction_markets":
            return self._build_prediction_card(request, context, tool_outputs, tool_traces)
        if domain == "crypto":
            return self._build_crypto_card(request, context, tool_outputs, tool_traces)
        if domain == "fundamentals":
            return self._build_fundamentals_card(request, context, tool_outputs, tool_traces)
        if domain == "risk":
            return self._build_risk_card(request, context, tool_outputs, tool_traces)
        if domain == "iv":
            return self._build_iv_card(request, context, tool_outputs, tool_traces)
        if domain == "strategy_lab":
            return self._build_strategy_lab_card(request, context, tool_outputs, tool_traces)
        if domain == "synthesis":
            return self._build_synthesis_card(request, context, tool_outputs, tool_traces)
        return self._fallback_card(request, context, tool_traces)

    def _build_portfolio_card(
        self,
        request: CopilotResearchCardRequest,
        context: CopilotContextBundle,
        tool_outputs: dict[str, Any],
        tool_traces: list[CopilotToolTrace],
    ) -> ResearchCard:
        snapshot = self._as_dict(context.summary_data.get("snapshot"))
        performance = self._as_dict(tool_outputs.get("get_portfolio_performance_context")) or self._as_dict(
            context.summary_data.get("performance")
        )
        largest_position = self._as_dict(snapshot.get("largest_position"))
        largest_symbol = largest_position.get("symbol") or "the top position"
        cash_weight = self._as_float(snapshot.get("cash_weight"))
        relative_return = self._as_float(performance.get("relative_return"))
        benchmark = performance.get("benchmark_symbol") or "the benchmark"

        if cash_weight is not None and cash_weight >= 0.2:
            hypothesis = (
                "Cash and top-position concentration are large enough that deployment timing may matter more than broad market beta."
            )
        elif relative_return is not None and abs(relative_return) >= 0.03:
            hypothesis = (
                "Recent benchmark-relative slippage is large enough that the portfolio likely needs a top-exposure attribution pass."
            )
        else:
            hypothesis = "The active book is concentrated enough that top exposures and benchmark framing should be reviewed together."

        rationale = (
            f"The portfolio context includes {self._fmt_int(snapshot.get('positions_count'))} positions, "
            f"top exposure in {largest_symbol}, and a loaded performance overlay against {benchmark}."
        )
        required_data = [
            "Top exposures by base-market value",
            f"Benchmark-relative performance versus {benchmark}",
            "Cash weight and local-history drawdown context",
        ]
        confounders = [
            "Local history may be shorter than the current positioning regime.",
            "Benchmark-relative interpretation depends on the chosen benchmark.",
            "Unrealized P&L can overstate conviction changes during volatile sessions.",
        ]
        next_steps = [
            f"Review whether {largest_symbol} is driving most of the portfolio variance.",
            "Check whether cash weight is intentional dry powder or passive drag.",
            "Compare recent benchmark-relative drift against the local drawdown path.",
        ]
        caveats = [
            "This card was generated by Gamma's deterministic mock Copilot.",
            "It uses only the loaded Gamma portfolio context and read-only tools.",
        ]
        return ResearchCard(
            title=self._title("Portfolio", request.prompt),
            hypothesis=hypothesis,
            rationale=rationale,
            required_data=required_data,
            proposed_test=(
                f"Rank the largest positions by weight and unrealized P&L, then compare that concentration profile against "
                f"the recent relative return versus {benchmark}."
            ),
            confounders=confounders,
            next_steps=next_steps,
            caveats=caveats,
            source_backed_claims=[
                self._claim(
                    "Gamma has an active portfolio snapshot plus performance context available for this card.",
                    context,
                    tool_traces,
                )
            ],
            inferred_claims=[
                "Any conclusion about sizing changes or redeployment still requires user judgment.",
            ],
        )

    def _build_research_card(
        self,
        request: CopilotResearchCardRequest,
        context: CopilotContextBundle,
        tool_outputs: dict[str, Any],
        tool_traces: list[CopilotToolTrace],
    ) -> ResearchCard:
        research = self._as_dict(context.summary_data.get("research"))
        structure = self._as_dict(research.get("structure"))
        coverage = self._as_dict(tool_outputs.get("get_research_coverage_context")) or self._as_dict(
            research.get("coverage")
        )
        primary_symbol = research.get("primary_symbol") or "the active scope"
        scope_type = research.get("scope_type") or "research scope"
        top_weight = self._as_float(structure.get("top_weight"))
        effective_positions = self._as_float(structure.get("effective_positions"))

        if top_weight is not None and top_weight >= 0.5:
            hypothesis = "The active research scope is concentrated enough that a single-name driver may dominate the conclusion."
        elif effective_positions is not None and effective_positions >= 4:
            hypothesis = "The active research scope is diversified enough to justify a cleaner benchmark-relative comparison."
        else:
            hypothesis = "The active research scope is coherent enough to refine into a sharper benchmark-relative question."

        rationale = (
            f"Gamma already has a {scope_type.replace('_', ' ')} result for {primary_symbol}, "
            f"including structure, constituent contribution, and coverage diagnostics."
        )
        missing = coverage.get("missing_symbols") or []
        missing_label = ", ".join(str(item) for item in missing[:4]) if missing else "none"
        return ResearchCard(
            title=self._title("Research", request.prompt),
            hypothesis=hypothesis,
            rationale=rationale,
            required_data=[
                "Current weight structure",
                "Constituent return and weighted-return breakdown",
                "Coverage and benchmark-overlap diagnostics",
            ],
            proposed_test=(
                "Compare the top-weighted constituents against the weakest contributor, then check whether the observed "
                "conclusion survives the current coverage and benchmark-overlap constraints."
            ),
            confounders=[
                "Synthetic scopes can hide name-level concentration behind normalized weights.",
                f"Missing history currently reported: {missing_label}.",
                "Benchmark overlap can thin out faster than the headline constituent count implies.",
            ],
            next_steps=[
                "Inspect the weighted leader and worst constituent together rather than in isolation.",
                "Confirm whether missing symbols change the apparent edge.",
                "Decide whether the next run should tighten the scope or change the benchmark lens.",
            ],
            caveats=[
                "This card was generated by Gamma's deterministic mock Copilot.",
                "It does not infer beyond the currently loaded research result and tool outputs.",
            ],
            source_backed_claims=[
                self._claim(
                    "Gamma has an active research result plus scope and coverage drilldowns available for this card.",
                    context,
                    tool_traces,
                )
            ],
            inferred_claims=[
                "The cleanest next research question depends on what benchmark or comparison set you actually care about.",
            ],
        )

