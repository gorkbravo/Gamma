    def _claim(
        self,
        text: str,
        context: CopilotContextBundle,
        tool_traces: list[CopilotToolTrace],
    ) -> ResearchClaim:
        evidence_refs: list[str] = []
        for source in context.sources[:2]:
            evidence_refs.append(source.source_id)
        for trace in tool_traces:
            for source_id in trace.source_ids:
                if source_id not in evidence_refs:
                    evidence_refs.append(source_id)
        return ResearchClaim(claim=text, evidence_refs=evidence_refs)

    def _infer_macro_series_id(self, summary_data: dict[str, Any]) -> str | None:
        for card in self._as_list(summary_data.get("snapshot_cards")):
            for metric in self._as_list(self._as_dict(card).get("metrics")):
                series_id = str(self._as_dict(metric).get("series_id") or "").strip()
                if series_id:
                    return series_id
        rates_policy = self._as_dict(summary_data.get("rates_policy"))
        for key in ("policy_metrics", "real_yield_metrics"):
            for metric in self._as_list(rates_policy.get(key)):
                series_id = str(self._as_dict(metric).get("series_id") or "").strip()
                if series_id:
                    return series_id
        return None

    def _title(self, domain_label: str, prompt: str | None) -> str:
        prompt_text = str(prompt or "").strip()
        if not prompt_text:
            return f"{domain_label} Research Card"
        trimmed = " ".join(prompt_text.split())
        return f"{domain_label}: {trimmed[:68]}"

    def _response_id(self, request: CopilotResearchCardRequest) -> str:
        seed = "|".join(
            [
                str(request.user_session_id or "anonymous"),
                str(request.domain or ""),
                str(request.previous_response_id or ""),
                str(request.prompt or ""),
            ]
        )
        digest = sha256(seed.encode("utf-8")).hexdigest()[:16]
        return f"mock_{request.domain}_{digest}"

    @staticmethod
    def _as_dict(value: Any) -> dict[str, Any]:
        return value if isinstance(value, dict) else {}

    @staticmethod
    def _as_list(value: Any) -> list[Any]:
        return value if isinstance(value, list) else []

    @staticmethod
    def _as_float(value: Any) -> float | None:
        try:
            numeric = float(value)
        except (TypeError, ValueError):
            return None
        if numeric != numeric:
            return None
        return numeric

    @staticmethod
    def _fmt_int(value: Any) -> str:
        try:
            return f"{int(value):d}"
        except (TypeError, ValueError):
            return "0"
